"""Pure data contracts for site configurations.

These Pydantic models define the schema that the LLM generates and the fixed
scraping engine interprets. No executable code is present here.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import Literal
from pydantic import BaseModel, Field


class SelectorType(str, Enum):
    CSS = "css"
    XPATH = "xpath"


class ExtractionType(str, Enum):
    TEXT = "text"
    CLEAN_TEXT = "clean_text"
    ATTRIBUTE = "attribute"
    MARKDOWN = "markdown"


class FetchStrategy(str, Enum):
    STATIC = "static"
    STEALTH = "stealth"
    DYNAMIC = "dynamic"


class PaginationStrategy(str, Enum):
    NONE = "none"
    NEXT_LINK = "next_link"
    PAGE_NUMBER = "page_number"
    INFINITE_SCROLL = "infinite_scroll"


class FieldMapping(BaseModel):
    """Specification of how to extract a single logical field from an item container."""

    field_name: str = Field(
        description="Logical field name matching JobPosting attribute (e.g. 'title', 'company', 'url', 'salary', 'location')"
    )
    selector: str = Field(
        description="CSS or XPath selector relative to the job item container"
    )
    selector_type: SelectorType = Field(
        default=SelectorType.CSS,
        description="Whether the selector is CSS or XPath"
    )
    extraction: ExtractionType = Field(
        default=ExtractionType.CLEAN_TEXT,
        description="Extraction method to use on matched element"
    )
    attribute_name: str | None = Field(
        default=None,
        description="Attribute name to extract if extraction == 'attribute' (e.g., 'href', 'data-id')"
    )
    regex_pattern: str | None = Field(
        default=None,
        description="Optional regex to apply to extracted text to extract specific subgroup"
    )
    required: bool = Field(
        default=False,
        description="Whether this field must be non-empty for a record to be valid"
    )
    default_value: str | None = Field(
        default=None,
        description="Fallback value if element is not found and field is optional"
    )


class PaginationRule(BaseModel):
    """Rules defining how to navigate across multiple pages."""

    strategy: PaginationStrategy = Field(
        default=PaginationStrategy.NONE,
        description="Pagination method to use"
    )
    next_link_selector: str | None = Field(
        default=None,
        description="CSS/XPath selector for the 'Next' link or button"
    )
    next_link_attribute: str = Field(
        default="href",
        description="Attribute containing next URL (usually 'href')"
    )
    url_template: str | None = Field(
        default=None,
        description="URL pattern with {page} placeholder for PAGE_NUMBER pagination"
    )
    start_page: int = Field(
        default=1,
        description="Initial page number"
    )
    page_param: str = Field(
        default="page",
        description="Query parameter name for page number"
    )
    max_pages: int = Field(
        default=3,
        ge=1,
        le=50,
        description="Upper bound on total pages to fetch in one scraping run"
    )
    scroll_count: int = Field(
        default=3,
        ge=1,
        le=20,
        description="Number of scrolls for INFINITE_SCROLL"
    )


class SiteConfig(BaseModel):
    """Complete declarative configuration for a single job site.

    This is the data structure generated by humans or LLMs and consumed
    by the fixed GenericListScraper engine.
    """

    site_name: str = Field(
        description="Unique identifier for the site (e.g. 'remoteok', 'indeed')"
    )
    base_url: str = Field(
        description="Starting URL or domain base for the job board"
    )
    container_selector: str = Field(
        description="CSS or XPath selector matching each individual job item block"
    )
    container_selector_type: SelectorType = Field(
        default=SelectorType.CSS,
        description="Whether container_selector is CSS or XPath"
    )
    fields: list[FieldMapping] = Field(
        description="List of field mappings to extract from each job container"
    )
    pagination: PaginationRule = Field(
        default_factory=PaginationRule,
        description="Pagination navigation rules"
    )
    fetch_strategy: FetchStrategy = Field(
        default=FetchStrategy.STATIC,
        description="Which fetcher engine to use (static HTTP, stealth, or dynamic browser)"
    )
    crawl_delay_seconds: float = Field(
        default=2.0,
        ge=0.0,
        description="Politeness delay between requests"
    )
    version: int = Field(
        default=1,
        description="Schema/config revision version number"
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when this config was authored or healed"
    )
    healing_summary: str | None = Field(
        default=None,
        description="Audit note describing why/how this config version was created"
    )
